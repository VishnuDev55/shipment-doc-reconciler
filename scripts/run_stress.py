"""Run the harder stress inputs live and score the transcription per field.

Each case is a single document generated by build_stress_inputs.py with a
truth.json. This replays nothing — a scratch cache forces one live NVIDIA vision
call per case — then compares the model's transcription (normalized, the same
way the engine sees it) against the ground truth, and reports the absent-field
behaviour explicitly: a field the page does not print must come back absent,
never invented.

    python scripts/run_stress.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import spend  # noqa: E402
from app.config import Settings  # noqa: E402
from app.fields import FIELD_ORDER  # noqa: E402
from app.models import ExtractedField  # noqa: E402
from app.normalize import normalize_field  # noqa: E402
from app.orchestrator import Reconciler  # noqa: E402
from app.providers import vision_endpoint  # noqa: E402

STRESS = ROOT / "runs" / "stress"
CASES = ("phone_photo", "two_page", "german", "absent")


def _expected_canonical(field: str, raw: str | None) -> str | None:
    if raw is None:
        return None
    norm = normalize_field(field, ExtractedField(
        present=True, value=raw, evidence_text=raw, page_index=1, confidence=1.0))
    return norm.canonical


async def run_case(rec: Reconciler, name: str, truth: dict,
                   timeout: float = 180.0) -> dict:
    import time

    files = sorted(STRESS.glob(f"{name}.*"))
    upload = next(f for f in files if f.suffix in (".png", ".pdf"))
    started = time.perf_counter()
    sid, _ = await rec.create_shipment(
        [(upload.name, truth["doc_type"], upload.read_bytes())]
    )
    try:
        await rec.wait(sid, timeout=timeout)
    except TimeoutError:
        elapsed = time.perf_counter() - started
        print(f"  HUNG: no response from the vision host within {timeout}s "
              f"(the request sat waiting for headers; the run was cancelled)")
        return {
            "case": name, "verdict": None, "banner": None, "doc_status": "hung",
            "elapsed_s": elapsed, "tokens": 0, "correct": 0, "checked": 0,
            "invented": [], "fields": {},
        }
    report = rec.get(sid)
    elapsed = time.perf_counter() - started
    assert report is not None

    doc = report.documents[0]
    fields: dict[str, dict] = {}
    correct = 0
    checked = 0
    invented: list[str] = []
    for field in FIELD_ORDER:
        want = truth["fields"].get(field)
        ext = doc.extraction.fields.get(field) if doc.extraction else None
        got_present = bool(ext and ext.present)
        got_canonical = None
        if ext and ext.present:
            got_canonical = doc.normalized.get(field).canonical if doc.normalized.get(field) else None
            if got_canonical is None and ext.value:
                got_canonical = normalize_field(field, ext).canonical
        expected = _expected_canonical(field, want)

        if want is None:
            # Absent in truth: the only acceptable answer is "not present".
            ok = not got_present
            if got_present:
                invented.append(field)
        else:
            ok = got_present and got_canonical == expected
        checked += 1
        if ok:
            correct += 1
        fields[field] = {
            "want": want, "expected_canonical": expected,
            "got_present": got_present,
            "got_canonical": got_canonical, "got_raw": (ext.value if ext else None),
            "ok": ok,
        }

    record_report_spend(report)
    return {
        "case": name, "verdict": report.summary.verdict,
        "banner": report.status_report.banner,
        "doc_status": doc.status, "elapsed_s": elapsed,
        "tokens": doc.usage.total if doc.usage else 0,
        "correct": correct, "checked": checked, "invented": invented,
        "fields": fields,
    }


def record_report_spend(report) -> int:
    added = 0
    for doc in report.documents:
        u = doc.usage
        if u and (u.prompt or u.completion or u.total):
            spend.record(doc.provider, doc.model,
                         {"prompt": u.prompt, "completion": u.completion},
                         note=f"stress {doc.label}")
            added += 1
    return added


async def main() -> int:
    if not Path(".env").is_file():
        print("BLOCKED: no .env")
        return 2
    from dotenv import dotenv_values

    env = dotenv_values(ROOT / ".env")
    preprocess = "--preprocess" in sys.argv
    settings = Settings(
        _env_file=None,
        demo_mode=False,
        vision_provider=env.get("VISION_PROVIDER", "nvidia"),
        nvidia_api_key=env.get("NVIDIA_API_KEY", ""),
        nebius_api_key=env.get("NEBIUS_API_KEY", ""),
        nvidia_base_url=env.get("NVIDIA_BASE_URL",
                                 "https://integrate.api.nvidia.com/v1/"),
        nebius_base_url=env.get("NEBIUS_BASE_URL",
                                 "https://api.tokenfactory.nebius.com/v1/"),
        nebius_vision_model=env.get("NEBIUS_VISION_MODEL", ""),
        enable_summary=False,
        enable_adjudication=False,
        enable_briefing=False,
        consensus=False,
        enable_line_items=False,
        preprocess_orientation=preprocess,
        runs_dir=ROOT / "runs" / "stress_runs",
        cache_dir=ROOT / "runs" / "stress_cache",
    )
    endpoint = vision_endpoint(settings)
    if not endpoint.api_key.strip():
        print(f"BLOCKED: no API key for vision provider '{endpoint.provider}'")
        return 2

    rec = Reconciler(settings)
    print(f"vision: {rec.client.endpoint.provider} / {rec.client.endpoint.model} "
          f"(preprocess={preprocess})\n")
    names = [a for a in sys.argv[1:] if a != "--preprocess"] or list(CASES)
    rows = []
    for name in names:
        if name not in CASES:
            print(f"unknown case {name!r}; choose from {list(CASES)}")
            return 2
        truth = json.loads((STRESS / f"{name}.truth.json").read_text(encoding="utf-8"))
        print(f"===== {name}  ({truth['note']}) =====")
        r = await run_case(rec, name, truth, timeout=150.0)
        rows.append(r)
        if not r["fields"]:
            continue
        for field in FIELD_ORDER:
            f = r["fields"][field]
            if f["want"] is None:
                got = "absent" if not f["got_present"] else f"INVENTED {f['got_raw']!r}"
            else:
                got = f["got_canonical"] if f["got_present"] else "absent"
            mark = "ok" if f["ok"] else "FAIL"
            print(f"  [{mark}] {field:18} want={f['expected_canonical']!r:28} got={got!r}")
        print(f"  verdict={r['verdict']} banner={r['banner']} "
              f"doc={r['doc_status']} {r['elapsed_s']:.0f}s {r['tokens']} tok "
              f"correct={r['correct']}/{r['checked']} invented={r['invented'] or 'none'}")

    total_correct = sum(r["correct"] for r in rows)
    total_checked = sum(r["checked"] for r in rows)
    if total_checked:
        print(f"\n===== total: {total_correct}/{total_checked} fields transcribed "
              f"correctly ({100 * total_correct / total_checked:.0f}%) =====")
    else:
        print("\n===== total: every case hung — no fields were transcribed =====")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
